type MessageKey = keyof typeof MESSAGES.en;
type Params = Record<string, string | number | null | undefined>;

export function t(key: MessageKey, params?: Params): string {
  return tForLang(getActiveLang(), key, params);
}

export function tForLang(lang: Lang, key: MessageKey, params?: Params): string {
  const catalog = MESSAGES[normalizeLang(lang)] as Partial<Record<MessageKey, string>>;
  const fallback = MESSAGES.en[key] ?? key;
  const template = catalog[key] ?? fallback;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function labelForStatus(status: string | null | undefined): string {
  if (!status) return "—";
  const key = `status.${status}` as MessageKey;
  const catalog = MESSAGES[getActiveLang()] as Partial<Record<MessageKey, string>>;
  return catalog[key] ?? MESSAGES.en[key] ?? status.replace(/_/g, " ");
}

export function labelForMethod(method: string | null | undefined): string {
  if (!method) return "—";
  const key = `method.${method}` as MessageKey;
  const catalog = MESSAGES[getActiveLang()] as Partial<Record<MessageKey, string>>;
  return catalog[key] ?? MESSAGES.en[key] ?? method.replace(/_/g, " ");
}

export function useI18n() {
  const lang = useSyncExternalStore(subscribeToLang, getActiveLang, getActiveLang);
  return { lang, dir: getDirection(lang), locale: getLocale(), t };
}
